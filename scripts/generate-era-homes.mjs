import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const manifest = JSON.parse(readFileSync(resolve(root, 'assets/era-homes.json'), 'utf8'))
const homes = manifest.eras.flatMap((era) => era.homes.map((home) => ({ ...home, ...Object.fromEntries(Object.entries(era).filter(([key]) => key !== 'homes')) })))
if (manifest.eras.length !== 35 || manifest.eras.some((era) => era.homes.length !== 30)) throw new Error('Expected 30 homes for every one of the 35 eras')
for (const field of ['kind', 'wire']) if (new Set(homes.map((home) => home[field])).size !== homes.length) throw new Error(`Duplicate ${field}`)
const generated = '// Generated by scripts/generate-era-homes.mjs from assets/era-homes.json.\n'
const outputs = new Map()
let buildings = readFileSync(resolve(root, 'simulation/sim-core/src/sim/tech/buildings.rs'), 'utf8')
for (const [marker, indent] of [['ERA_HOME_ENUM', '    '], ['ERA_HOME_ALL', '            ']]) {
  const replacement = `// BEGIN ${marker}\n${homes.map((home) => `${indent}${home.kind},`).join('\n')}\n${indent}// END ${marker}`
  const expression = new RegExp(`// BEGIN ${marker}[\\s\\S]*?// END ${marker}`)
  if (!expression.test(buildings)) throw new Error(`Missing ${marker}`)
  buildings = buildings.replace(expression, replacement)
}
outputs.set('simulation/sim-core/src/sim/tech/buildings.rs', buildings)
let rust = generated + 'use super::buildings::BuildingKind;\nuse crate::sim::era::Era;\n\n'
rust += '#[derive(Clone, Copy, Debug)]\npub struct EraHomeSpec {\n    pub name: &\'static str,\n    pub era: Era,\n    pub footprint: (u8, u8),\n    pub capacity: u8,\n}\n\n'
rust += 'pub fn spec(kind: BuildingKind) -> Option<EraHomeSpec> {\n    use BuildingKind::*;\n    let (name, era, width, height, capacity) = match kind {\n'
rust += homes.map((h) => `        ${h.kind} => ("${h.wire}", Era::${h.rustEra}, ${h.footprint[0]}, ${h.footprint[1]}, ${h.capacity}),`).join('\n')
rust += '\n        _ => return None,\n    };\n    Some(EraHomeSpec { name, era, footprint: (width, height), capacity })\n}\n\n'
rust += 'pub fn for_era(era: Era) -> &\'static [BuildingKind] {\n    use BuildingKind::*;\n    match era {\n'
rust += manifest.eras.map((e) => `        Era::${e.rustEra} => &[${e.homes.map((h) => h.kind).join(', ')}],`).join('\n')
rust += '\n    }\n}\n'
outputs.set('simulation/sim-core/src/sim/tech/era_homes.rs', rust)
let ts = generated + "export interface EraHome {\n  kind: string\n  wire: string\n  label: string\n  era: string\n  family: number\n  wall: string\n  roof: string\n  accent: string\n  motif: number\n  form: number\n  layout: number\n  footprint: [number, number]\n  capacity: number\n}\n\n"
ts += 'type HomeRow = [kind: string, form: number, layout: number, width: number, height: number, capacity: number]\n'
ts += 'interface HomeGroup { era: string; prefix: string; family: number; wall: string; roof: string; accent: string; motif: number; homes: HomeRow[] }\n\n'
ts += 'const GROUPS: HomeGroup[] = [\n'
for (const era of manifest.eras) {
  const metadata = Object.fromEntries(Object.entries(era).filter(([key]) => !['homes', 'rustEra'].includes(key)))
  metadata.prefix = era.rustEra
  ts += `  { ...${JSON.stringify(metadata)}, homes: [\n`
  ts += era.homes.map((h) => `    ${JSON.stringify([h.kind, h.form, h.layout, ...h.footprint, h.capacity])},`).join('\n')
  ts += '\n  ] },\n'
}
ts += ']\n\nexport const ERA_HOMES: readonly EraHome[] = GROUPS.flatMap(({ homes, prefix, ...style }) => homes.map(([kind, form, layout, width, height, capacity]) => ({ ...style, kind, wire: kind.replace(/([a-z0-9])([A-Z])/g, \'$1_$2\').toLowerCase(), label: kind.slice(prefix.length).replace(/([a-z])([A-Z])/g, \'$1 $2\'), form, layout, footprint: [width, height] as [number, number], capacity })))\n\n'
ts += 'const byKind = new Map(ERA_HOMES.flatMap((home) => [[home.kind.toLowerCase(), home], [home.wire, home]] as const))\nexport function eraHome(kind: string): EraHome | undefined {\n  return byKind.get(kind.toLowerCase())\n}\n'
outputs.set('client/src/2d/world/era-home-catalog.ts', ts)
// Formatting is part of generation so --check is stable after normal repo formatting.
const prettier = await import(resolve(root, 'client/node_modules/prettier/index.mjs'))
for (const [path, contents] of outputs) {
  let formatted = contents
  if (path.endsWith('.ts')) formatted = await prettier.format(contents, { parser: 'typescript', semi: false, singleQuote: true, trailingComma: 'all', printWidth: 110 })
  if (path.endsWith('.rs') && path.includes('era_homes')) {
    const { spawnSync } = await import('node:child_process')
    const result = spawnSync('rustfmt', ['--edition', '2021', '--config-path', resolve(root, 'simulation/rustfmt.toml'), '--emit', 'stdout'], { input: contents, encoding: 'utf8' })
    if (result.status !== 0) throw new Error(result.stderr)
    formatted = result.stdout
  }
  if (process.argv.includes('--check')) {
    if (readFileSync(resolve(root, path), 'utf8') !== formatted) throw new Error(`Stale generated file: ${path}`)
  } else writeFileSync(resolve(root, path), formatted)
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${homes.length} homes across ${manifest.eras.length} eras`)
