function fnv(text: string): string {
  let h = 2166136261
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    h = Math.imul(h, 16777619) >>> 0
  }
  return h.toString(16).padStart(8, '0')
}

function allIcons(): string[] {
  const icons = new Set<string>(HEADER_ICONS)
  icons.add('not-a-real-icon')
  for (const category of SANDBOX_CATEGORIES) {
    icons.add(category.icon)
    for (const tool of category.tools) icons.add(tool.icon)
  }
  return [...icons].sort()
}

