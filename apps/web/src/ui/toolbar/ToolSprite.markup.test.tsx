describe('ToolSprite markup', () => {
  it('is byte-identical to the markup rendered before the element cache existed', () => {
    const actual: Record<string, string> = {}
    for (const icon of allIcons()) {
      actual[`${icon}@24`] = fnv(renderToStaticMarkup(<ToolSprite icon={icon} />))
      actual[`${icon}@16`] = fnv(renderToStaticMarkup(<ToolSprite icon={icon} size={16} />))
    }
    expect(actual).toEqual(GOLDEN)
  })

  it('renders the same markup on repeated renders', () => {
    for (const icon of ['🚶', '🌙', 'not-a-real-icon']) {
      const first = renderToStaticMarkup(<ToolSprite icon={icon} />)
      expect(renderToStaticMarkup(<ToolSprite icon={icon} />)).toBe(first)
    }
  })
})
