// Pairs a baseline and an updated sim-core wasm build on one saved world.
//
// It asserts every full and delta frame is byte-identical, so it is a
// correctness check first, and reports the median and mean of the per-frame
// `deltaFrame()`/`JSON.parse` timings second. A few warm-up frames are run
// before timing so JIT and first-frame allocations do not dominate a short run
// at the ~1 ms scale.
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const [baselineDir, updatedDir, savePath, framesArg = '10'] = process.argv.slice(2)
if (!baselineDir || !updatedDir || !savePath) {
  throw new Error(
    'usage: node bench/wasm-frame-ab.mjs <baseline-wasm-dir> <updated-wasm-dir> <save.bin> [frames]',
  )
}
const frameCount = Number(framesArg)
if (!Number.isInteger(frameCount) || frameCount < 1) throw new Error('frames must be a positive integer')

// A save generated by `gen-save.mjs` is a `.bin` beside a `.json` with the seed.
const metaPath = path.join(
  path.dirname(savePath),
  `${path.basename(savePath, path.extname(savePath))}.json`,
)
const meta = JSON.parse(readFileSync(metaPath, 'utf8'))
const save = readFileSync(savePath)
async function load(dir, label) {
  const resolved = path.resolve(dir)
  const mod = await import(`${pathToFileURL(path.join(resolved, 'sim_core.js')).href}?${label}`)
  mod.initSync({ module: readFileSync(path.join(resolved, 'sim_core_bg.wasm')) })
  return mod.Sim.fromSerialized(BigInt(meta.seed), save)
}

const baseline = await load(baselineDir, 'baseline')
const updated = await load(updatedDir, 'updated')
const timestamp = 1_700_000_000_000
const baselineFull = baseline.fullFrame(1, timestamp)
const updatedFull = updated.fullFrame(1, timestamp)
assert.equal(updatedFull, baselineFull, 'full frame JSON bytes changed')

// Warm both modules on the same frames before timing.
const WARMUP = 5
for (let i = 0; i < WARMUP; i += 1) {
  baseline.tickN(1)
  updated.tickN(1)
  assert.equal(
    updated.deltaFrame(i + 2, timestamp),
    baseline.deltaFrame(i + 2, timestamp),
    `warm-up delta ${i} JSON bytes changed`,
  )
}

const baselineFrameMs = []
const updatedFrameMs = []
const baselineParseMs = []
const updatedParseMs = []
let totalBytes = 0
for (let i = 0; i < frameCount; i += 1) {
  const frameId = WARMUP + i + 2
  baseline.tickN(1)
  updated.tickN(1)

  let start = performance.now()
  const baselineFrame = baseline.deltaFrame(frameId, timestamp)
  baselineFrameMs.push(performance.now() - start)
  start = performance.now()
  const updatedFrame = updated.deltaFrame(frameId, timestamp)
  updatedFrameMs.push(performance.now() - start)
  assert.equal(updatedFrame, baselineFrame, `delta frame ${i} JSON bytes changed`)
  totalBytes += Buffer.byteLength(updatedFrame)

  start = performance.now()
  JSON.parse(baselineFrame)
  baselineParseMs.push(performance.now() - start)
  start = performance.now()
  JSON.parse(updatedFrame)
  updatedParseMs.push(performance.now() - start)
}

function median(samples) {
  const sorted = [...samples].sort((a, b) => a - b)
  const mid = sorted.length >> 1
  return sorted.length % 2 === 1 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2
}
function mean(samples) {
  return samples.reduce((sum, value) => sum + value, 0) / samples.length
}

console.log(
  JSON.stringify({
    frameCount,
    fullBytes: Buffer.byteLength(updatedFull),
    deltaBytesPerFrame: totalBytes / frameCount,
    baselineDeltaFrameMs: median(baselineFrameMs),
    updatedDeltaFrameMs: median(updatedFrameMs),
    baselineDeltaFrameMeanMs: mean(baselineFrameMs),
    updatedDeltaFrameMeanMs: mean(updatedFrameMs),
    baselineDeltaParseMs: median(baselineParseMs),
    updatedDeltaParseMs: median(updatedParseMs),
  }),
)
